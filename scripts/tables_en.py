# Palabras que delatan texto sin traducir (fuera de \texttt, \cite, \ref, \label y de las fórmulas).
SPANISH = re.compile(r"[áéíóúñÁÉÍÓÚÑ¿¡]|\b(de|del|la|las|los|el|con|sobre|en|que|por|sin|entre|una|y|se|al|lote|capa|"
                     r"capas|semillas?|épocas?|contra|cada|rama|ramas|datos|término|vecindad|igual)\b")
STRIP = re.compile(r"\\(texttt|cite|ref|label|emph\{pooling)\{[^}]*\}|\$[^$]*\$|^%.*$", re.M)


def translate(text: str) -> str:
    for es in sorted(PHRASES, key=len, reverse=True):
        text = text.replace(es, PHRASES[es])
    return text.replace(HEADER_ES, HEADER_EN, 1)


def leftovers(text: str) -> list[str]:
    return [line.strip() for line in STRIP.sub("", text).splitlines() if SPANISH.search(line)]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    bad = 0
    for src in SOURCES:
        en = translate(src.read_text())
        for line in leftovers(en):
            print(f"{src.name}: sin traducir: {line[:160]}", file=sys.stderr)
            bad += 1
        (OUT / src.name).write_text(en)
    print(f"{len(SOURCES)} tablas en {OUT}" + (f"; {bad} líneas sin traducir" if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
